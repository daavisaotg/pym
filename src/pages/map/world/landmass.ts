export const WORLD = { w: 1600, h: 620, north: 80, south: -59.5 };

/** Projeção equirretangular para o quadro do Explorar. */
export function project([lon, lat]: LL): [number, number] {
  const k = WORLD.w / 360;
  return [(lon + 180) * k, (WORLD.north - lat) * k];
}

function inside([x, y]: LL, poly: LL[]) {
  let c = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
}

/** Pontos de terra numa grade regular, prontos para virar um único <path>. */
export function dotPath(step = 1.5, size = 3.2): string {
  const parts: string[] = [];
  const boxes = LANDMASS.map((p) => {
    const xs = p.map((q) => q[0]);
    const ys = p.map((q) => q[1]);
    return [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)];
  });
  for (let lat = WORLD.north - step / 2; lat > WORLD.south; lat -= step) {
    // Pontos alternados por linha, como numa retícula
    const offset = (Math.round((WORLD.north - lat) / step) % 2) * (step / 2);
    for (let lon = -180 + step / 2 + offset; lon < 180; lon += step) {
      const hit = LANDMASS.some((p, i) => {
        const b = boxes[i];
        return lon >= b[0] && lon <= b[2] && lat >= b[1] && lat <= b[3] && inside([lon, lat], p);
      });
      if (!hit) continue;
      const [x, y] = project([lon, lat]);
      parts.push(`M${(x - size / 2).toFixed(1)} ${(y - size / 2).toFixed(1)}h${size}v${size}h-${size}z`);
    }
  }
  return parts.join('');
}
